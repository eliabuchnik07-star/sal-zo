def _is_alcohol(name):
    toks = tokens(name)
    s = set(toks) | {a + "_" + b for a, b in zip(toks, toks[1:])}
    if s & NOT_ALCOHOL or re.search(r"(ללא|נטול\S*) ?אלכ|0\.0", name or ""):
        return False
    return bool(s & ALCOHOL)


