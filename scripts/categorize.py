def tokens(name):
    s = (name or "").lower()
    s = re.sub(r"[\"'`״׳]", "", s)               # צ'יפס -> ציפס, תפו"א -> תפוא
    s = re.sub(r"(\d)([א-ת])", r"\1 \2", s)       # 500גרם -> 500 גרם
    s = re.sub(r"([א-ת])(\d)", r"\1 \2", s)
    s = re.sub(r"[^\w%]+", " ", s)                # punctuation -> space
    return [t for t in s.split() if t]


