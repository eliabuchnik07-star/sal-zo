def _head(toks):
    i = 0
    while i < len(toks) - 1 and (toks[i] in NOISE or NUM.match(toks[i])):
        i += 1
    return i


VOLUME = re.compile(r"\d+ ?(מל|מ|ליטר|ל|ml)\b")


def _produce(toks, flavored, name):
    s = set(toks) | {t[1:] for t in toks if len(t) > 3 and t[0] == "ו"}
    if toks and toks[_head(toks)] in ("בצל", "שום", "בצלים") and len(s & TO_SNACKS) == len(s & W("יבש יבשים")):
        s -= W("יבש יבשים")  # "בצל יבש" is a fresh onion
    if VOLUME.search(" ".join(toks)) and not (s & TO_DRINKS):
        return "pantry"  # sauces and jars are sold by volume, fresh produce is not
    if s & TO_DRINKS:
        return "drinks"
    if flavored:
        return None
    if s & TO_DELI:
        return "deli"
    if s & TO_SNACKS:
        return "snacks"
    if s & TO_PANTRY:
        return "pantry"
    return "fruit"


