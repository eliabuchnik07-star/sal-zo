def _refine(c, name):
    if c not in ("pantry", "snacks", "fruit", "meat", "deli"):
        return c
    toks = tokens(name)
    if not toks:
        return c
    s = set(toks)
    h = toks[_head(toks)]
    if c in ("pantry", "snacks") and not (s & NOT_BAKING):
        if c == "pantry" and (h in BAKING_HEAD or s & BAKING_WORDS):
            if not (h == "סוכר" and s & W("קנים")):
                return "baking"
        if c == "snacks" and s & (BAKING_WORDS | W("לבישול")) and h in W("שוקולד שבבי סוכריות שקדים אגוזי קוקוס"):
            return "baking"
        if h in W("אבקת תערובת") and s & (BAKING_WORDS | W("פודינג אפיה סופגניות עוגה חלה מאפינס")):
            return "baking"
    if c in ("pantry", "meat", "deli") and not (s & NOT_CANNED) and h not in W("רוטב ממרח מרק ציר"):
        if s & CANNED_WORDS and h in CANNED_HEAD or s & W("שימורי שימורים משומר משומרים בסירופ"):
            return "canned"
        if c == "pantry" and h in W("טונה סרדינים סרדין שפרוטים מקרל זיתים זית חמוצים קורנישון קורנישונים לפתן קומפוט רסק"):
            return "canned"
        if c == "pantry" and h in W("תירס אפונה") and s & W("גמדי מתוק ירוקה_שימורים") and not (s & W("לפופקורן קמח")):
            return "canned"
    return c


def _classify(name):
    toks = tokens(name)
    if not toks:
        return None
    s = set(toks)
    if s & EXCLUDE or toks[0] in CIGS or s & CLOTHES:
        return None
    if s & W("סבון סבונים"):
        return "home" if s & W("כלים לכלים כביסה לכביסה רצפה לרצפה ניקוי לניקוי כתמים אסלה לאסלה") else "care"
    if s & PETS:
        return "home"
    for cat, words in STRONG:
        if s & words:
            return cat
    if (s | {t[1:] for t in toks if t[:1] == "ו"}) & FROZEN and not (s & W("שקיות שקית פריזר")):
        t = toks[_head(toks)]
        if HEAD.get(t) == "meat" and t not in ("נאגטס", "שניצל", "קציצות"):
            return "meat"  # frozen chicken/beef/fish stay with meat
        return "frozen"
    cut = next((i for i, t in enumerate(toks) if t in FLAVOR and i > 0), len(toks))
    flavored = cut < len(toks)
    core = toks[:cut]
    i = _head(core)
    h = core[i]
    h2 = h + " " + core[i + 1] if i + 1 < len(core) else ""
    h3 = h2 + " " + core[i + 2] if i + 2 < len(core) else ""
    for ph in (h3, h2):
        if ph and ph in PHRASE:
            return PHRASE[ph]

    if h in ("גביע", "גביעי") and s & W("סלט חציל כרוב אבוקדו חומוס טחינה מטבוחה ירקות"):
        return "deli"
    if h == "פרוסות":
        if s & W("גבינה גבינת טילזיטר צדר גאודה עמק מוצרלה אמנטל") or re.search(r"\d+(\.\d+)?%", name):
            return "dairy"
        if s & W("עגל בקר עוף הודו פרגית"):
            return "meat"
    if h == "לבבות" and not (s & W("חסה קיסר")):
        return "meat"  # chicken hearts
    if h in PRODUCE:
        if h in HERBS and GRAMS.search(" ".join(toks)) and not (s & FRESH_HINT):
            return "pantry"  # dried herb or spice jar
        if h in ("תירס", "אפונה", "שעועית") and not (s & W("קלח קלחי קלחים טרי טריה טריים בתרמיל ארוז ארוזה משקל במשקל תפזורת")):
            return "pantry"
        if h == "שרי" and not (s & W("עגבניות עגבניה עגבנית")):
            return None if (s & W("יין משקה בירה")) else _produce(core, flavored, name)
        return _produce(core, flavored, name)

    if h in ("סלט", "סלטי") or h in DELI_HEAD:
        if s & W("פירות"):
            return "fruit" if not (s & (TO_PANTRY | TO_DRINKS)) else "pantry"
        if h == "חומוס" and (s & W("יבש גרגירים גרגירי שימורים מבושל קופסה שלם לבן גדול ענק יכין שורש קג סוגת")):
            return "pantry"
        return "deli"

    if h == "פירות" or h == "ירקות":
        return _produce(core, flavored, name)

    if h in ("גל", "גל.") or h == "ג" and i + 1 < len(core) and core[i + 1] in ("ל",):
        # "ג'ל" (gel) and "גל." (short for ice cream) both normalize to "גל"
        if s & W("קרמיסימו וניל שוקולד גלידה"):
            return "frozen"
        return _anywhere(core) or None

    if h == "סבון":
        return "home" if s & W("כלים לכלים כביסה לכביסה רצפה לרצפה ניקוי לניקוי כתמים אסלה לאסלה") else "care"
    if h == "נוזל":
        return "care" if s & W("עדשות לעדשות") else "home"
    if h == "מרכך":
        if s & W("כביסה לכביסה בדים מרוכז כביסות"):
            return "home"
        return "home" if re.search(r"\d ?(ליטר|ל)\b", " ".join(toks)) else "care"
    if h == "אבקת":
        if s & W("כביסה לכביסה ניקוי"):
            return "home"
        if s & W("חלבון פרוטאין"):
            return "care"
        return "pantry"
    if h in ("קפסולות", "קפסולה"):
        return "home" if s & W("כביסה לכביסה מדיח למדיח כלים") else "drinks"
    if h in ("טבליות", "טבלית"):
        return "home" if s & W("מדיח למדיח כלים כביסה לכביסה") else "care"
    if h == "טונה":
        return "meat" if s & W("סטייק פילה טרי טריה נתחי אדומה") else "pantry"
    if h in ("סרדינים", "סרדין", "שפרוטים", "מקרל"):
        return "pantry" if s & W("בשמן ברוטב שמן רוטב במים קופסה פחית") else "meat"
    if h == "מעדן":
        if s & W("בייקון פסטרמה נקניק הודו עוף"):
            return "meat"
        if s & (PRODUCE | W("100%")):
            return "pantry"
    if h == "שוק":
        return "meat" if s & W("עוף הודו עגל טלה כבש") else "snacks"
    if h == "סירופ":
        return "drinks" if s & W("פטל תפוזים תפוז לימון ענבים תות למשקה לימונענע אשכולית") else "pantry"
    if h == "עלי":
        if s & W("גפן"):
            return "pantry"
        if i + 1 < len(core) and core[i + 1] in PRODUCE | W("בייבי"):
            return _produce(core, flavored, name)
        return None
    if h == "תערובת":
        return "snacks" if s & W("אגוזים פירות סטודנטים לחטיף") else "pantry"
    if h == "מי":
        return "drinks"
    if h in ("חלב",) and s & W("גוף פנים ניקוי הסרת איפור"):
        return "care"
    if h == "שמן" and s & W("גוף לגוף פנים לפנים שיער לשיער תינוקות לתינוק עיסוי ארגן"):
        return "care"
    if h == "קרם":
        if s & W("קוקוס בלסמי פטיסייר לעוגה"):
            return "pantry"
        return "care"
    if h in ("מגבונים", "מגבוני"):
        return "home" if s & W("ניקוי לניקוי רצפה לרצפה חיטוי לחיטוי מטבח למטבח רב") else "care"
    if h == "פלמוליב":
        return "home" if s & W("כלים לכלים") else "care"
    if h == "פלפל" and s & W("שחור לבן אנגלי גרוס טחון ורוד קאיין שאטה"):
        return "pantry"
    if h in ("ציפס",) and s & W("תפוא תפוחי מוקפא קפוא לתנור"):
        return "frozen"
    if h in ("מיקס",):
        if s & W("ירקות עלים חסות פירות פלפלים"):
            return _produce(core, flavored, name)
        return "snacks"

    if h in ("שיפודי", "שיפודים", "שיפוד") and s & W("עוף פרגית פרגיות בקר כבש טלה הודו קבב בשר"):
        return "meat"
    if h in HEAD:
        c = HEAD[h]
        if c == "bread" and s & W("סלמון עוף בשר הודו דג"):
            return "meat"
        if c == "meat" and s & W("בשמן במים שימורים פחית קופסה בשמן_זית"):
            return "pantry"  # canned fish
        return c

    # brand or unknown first word: produce after it only with fresh-packaging words, else type words
    if i + 1 < len(core) and core[i + 1] in PRODUCE and s & W("ארוז ארוזה משקל במשקל ק מארז יחידה"):
        r = _produce(core[i + 1:], flavored, name)
        if r == "fruit":
            return r
    r = _anywhere(core)
    if r:
        return r
    if re.search(r"\b750 ?מל\b|\b700 ?מל\b|\b1 ?ליטר\b|\b1\.5 ?ליטר\b|\b2 ?ליטר\b|\b330 ?מל\b", " ".join(toks)):
        return "drinks"
    return None


def _anywhere(toks):
    cand = set(toks) | {t[1:] for t in toks if len(t) > 3 and t[0] in "ובלהמש"}
    for cat, words in ANYWHERE:
        if cand & words:
            return cat
    return None


# ---------- one category per barcode ----------
def load_overrides():
    try:
        with open(OVERRIDES_FILE, encoding="utf-8") as f:
            raw = json.load(f)
    except (OSError, ValueError):
        return {}
    return {str(k).lstrip("0"): (v if v in CAT_IDS else None) for k, v in raw.items() if not k.startswith("_")}


def assign(names_by_code, overrides=None):
    """{barcode: [names (or (name, maker)) from every chain]} -> {barcode: category id or None}. Majority vote."""
    overrides = load_overrides() if overrides is None else overrides
    out = {}
    for code, names in names_by_code.items():
        if code in overrides:
            out[code] = overrides[code]
            continue
        votes = Counter(classify(*(n if isinstance(n, tuple) else (n,))) for n in set(names) if n)
        known = [(c, k) for c, k in votes.most_common() if c]
        out[code] = known[0][0] if known else None
    return out


