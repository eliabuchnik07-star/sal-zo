@lru_cache(maxsize=None)
def classify(name, maker=""):
    """Category id for one product name, or None when we can't tell (it then shows only in search)."""
    c = _classify(name)
    if c == "fruit" and maker:
        for m, mc in MAKER_CAT.items():
            if m in maker:
                c = mc
                break
    c = _refine(c, name)
    if c == "drinks" and set(tokens(name)) & W("כוס כוסות גביע גביעי פותחן"):
        c = "home"  # glasses ("כוסות יין")
    elif c == "drinks" and _is_alcohol(name):
        c = "alcohol"
    return c


